import type { APIRoute } from "astro";
import { getCollection, type CollectionEntry } from "astro:content";
import { en } from "../data/copy/en";
import { DOCS_SIDEBAR } from "../data/docs-sidebar";

// /llms.txt (llmstxt.org): the English docs in the sidebar's groups and order, each page with its frontmatter title
// and description, so the list cannot drift from the docs. The Chinese pages mirror them under /zh/.
type Page = CollectionEntry<"docs">;

// The docs overview's opening paragraph (src/content/docs/docs/index.mdx), without its headline.
const ABOUT = "Each AI coding agent keeps its skills and settings in its own folder. HarnessKit shows all of them in one window: skills, MCP servers, plugins, hooks and CLIs, for every agent. One click adds a skill or MCP server to another agent. A security audit runs on your computer and gives each extension a trust score. Kits save skills, MCP servers and rules as a set you add to a project in one step. HarnessKit is free and open source, and runs as a desktop app, in the terminal, or in a browser.";

/** A directory's pages, its index included, in the order of Starlight's autogenerated groups: `sidebar.order`, then id. */
function pagesIn(pages: Page[], directory: string): Page[] {
  const order = (page: Page) => page.data.sidebar.order ?? Number.MAX_VALUE;
  return pages.filter(({ id }) => `${id}/`.startsWith(`${directory}/`)).sort((a, b) => order(a) - order(b) || a.id.localeCompare(b.id));
}

export const GET: APIRoute = async ({ site }) => {
  const pages = await getCollection("docs");
  const link = ({ id, data }: Page) => `- [${data.title}](${new URL(`/${id}/`, site)})${data.description ? `: ${data.description}` : ""}`;
  // The sidebar's external link (release notes) is not a docs page, so it gets no section.
  const sections = DOCS_SIDEBAR.flatMap(({ label, slug, autogenerate }) => {
    const listed = slug ? pages.filter(({ id }) => id === slug) : autogenerate ? pagesIn(pages, autogenerate.directory) : [];
    return listed.length ? [`## ${label}\n\n${listed.map(link).join("\n")}`] : [];
  });
  const chinese = `Each page is also in [Simplified Chinese](${new URL("/zh/docs/", site)}), at the same path under /zh/.`;
  return new Response(["# HarnessKit", `> ${en.footer.tagline}`, ABOUT, chinese, ...sections].join("\n\n") + "\n");
};
